#!/usr/bin/env python3
"""Regenerate the pinned MPL-2.0 PSL snapshot, including IDNA aliases."""
import argparse
import hashlib
import json
import pathlib
ROOT=pathlib.Path(__file__).resolve().parent
SHA256='809adae1a2cb1621b70165c11e0d14412d3f104f40a4ebed9a99e23c54f78d71'
parser=argparse.ArgumentParser(description=__doc__); parser.add_argument('snapshot',type=pathlib.Path); args=parser.parse_args()
data=args.snapshot.read_bytes()
if hashlib.sha256(data).hexdigest()!=SHA256: raise SystemExit('Public Suffix List snapshot hash mismatch')
rules=[]
for line in data.decode().splitlines():
    line=line.strip()
    if not line or line.startswith('//'): continue
    rules.append(line)
    marker='!' if line.startswith('!') else ('*.' if line.startswith('*.') else '')
    domain=line[len(marker):]
    alias=marker+'.'.join(label.encode('idna').decode('ascii') for label in domain.split('.'))
    if alias!=line: rules.append(alias)
notice='// Public Suffix List, MPL-2.0. Source: https://publicsuffix.org/list/public_suffix_list.dat\n// Snapshot SHA-256: '+SHA256+'\n// Generated by update-public-suffix.py; IDNA aliases added to Unicode rules.\n'
(ROOT/'MLPublicSuffixData.inc').write_text(notice+''.join(json.dumps(rule+'\n',ensure_ascii=False)+'\n' for rule in dict.fromkeys(rules)))
